"""Deterministic train subset sampler.

Creates a super-small train set from a larger list (e.g. super-fast).
Same --k + --seed always yields same 8 instances across all workers —
sampling happens once, workers read the resulting file, never resample.

Usage:
  uv run python scripts/sample_train.py --source super-fast-instances.txt --k 8 --seed 0
  uv run python scripts/sample_train.py --source super-fast-instances.txt --k all --seed 0
  uv run python scripts/sample_train.py --source super-fast-instances.txt --k 8 --seed 42 --out super-small-instances.txt
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import utcnow_iso  # noqa: E402


def parse_source(path: Path) -> list[str]:
    entries: list[str] = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            entries.append(line)
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description="Deterministic train subset sampler")
    ap.add_argument("--source", type=Path, required=True,
                    help="instance list file (e.g. super-fast-instances.txt)")
    ap.add_argument("--k", default="8",
                    help="number to sample, int or 'all' (default 8)")
    ap.add_argument("--seed", type=int, default=0,
                    help="RNG seed for deterministic shuffle (default 0)")
    ap.add_argument("--out", type=Path, default=None,
                    help="output file (default <source-stem>-small or super-small-instances.txt)")
    args = ap.parse_args()

    if not args.source.is_file():
        print(f"error: source not found: {args.source}")
        return 1

    entries = parse_source(args.source)
    if not entries:
        print(f"error: no instances in {args.source}")
        return 1

    if isinstance(args.k, str) and args.k.lower() == "all":
        chosen = entries
        k_label = "all"
    else:
        try:
            k = int(args.k)
        except ValueError:
            print(f"error: --k must be int or 'all', got {args.k!r}")
            return 1
        if k < 1:
            print("error: --k must be >=1 or 'all'")
            return 1
        if k > len(entries):
            print(f"error: --k={k} larger than source {len(entries)}")
            return 1
        rng = random.Random(args.seed)
        shuffled = entries[:]
        rng.shuffle(shuffled)
        chosen = sorted(shuffled[:k])  # sorted for stable diffable output
        k_label = str(k)

    out = args.out
    if out is None:
        # default next to source; handle both legacy and new miplib2017-*-instances naming
        stem = args.source.stem
        if stem in ("super-fast-instances", "miplib2017-super-fast-instances"):
            # miplib super-small is the train set
            if stem == "super-fast-instances":
                out = args.source.with_name("super-small-instances.txt")
            else:
                out = args.source.with_name("miplib2017-super-small-instances.txt")
        elif stem.endswith("-super-fast-instances"):
            # generic: <set>-super-fast-instances -> <set>-super-small-instances
            base = stem[:-len("-super-fast-instances")]
            out = args.source.with_name(f"{base}-super-small-instances.txt")
        else:
            out = args.source.with_name(f"{stem}-sample-{k_label}.txt")

    header = (
        f"# super-small train set - generated by scripts/sample_train.py - DO NOT EDIT BY HAND\n"
        f"# generated: {utcnow_iso()}\n"
        f"# source:    {args.source.name} ({len(entries)} instances)\n"
        f"# k:         {k_label}\n"
        f"# seed:      {args.seed}\n"
        f"# regenerate: uv run python scripts/sample_train.py --source {args.source.name} --k {k_label} --seed {args.seed}\n"
    )
    out.write_text(header + "".join(f"{e}\n" for e in chosen))
    print(f"source: {args.source} ({len(entries)})")
    print(f"sampled: {len(chosen)} (k={k_label}, seed={args.seed}) -> {out}")
    for e in chosen:
        print(f"  {e}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
