"""Classify MIPLIB2017 instances into benchmark sets from baseline timings.

Reads cached results for the upstream baseline version and splits solved
instances into:

    super-fast : baseline solves in <  --super-fast-below  (default 10 s)
    fast       : baseline solves in <  --fast-below        (default 60 s)

(super-fast is a subset of fast). Instances the baseline cannot solve within
the recorded time limit are only part of the implicit `full` set (all
instances, run with a 60 s cap).

The lists are machine- and options-dependent: regenerate them whenever the
machine or the baseline changes. Written files contain one instance name per
line plus a provenance header; they feed run_benchmark.py --instances-file.

Usage (from benchmark/):
    uv run python scripts/filter_sets.py                     # defaults below
    uv run python scripts/filter_sets.py --version 1.15.1 \
        --set miplib2017 --super-fast-below 10 --fast-below 60
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import results_dir, utcnow_iso  # noqa: E402

DEFAULT_BASELINE = "1.15.1"
DEFAULT_SET = "miplib2017"
DEFAULT_SUPER_FAST_BELOW = 10.0
DEFAULT_FAST_BELOW = 60.0

HEADER_TMPL = """\
# {name} set - generated by scripts/filter_sets.py - DO NOT EDIT BY HAND
# generated:   {date}
# machine:     {machine}
# baseline:    {solver} {version} (source sets: {src_sets}, {n_total} instances)
# criterion:   solved by baseline in < {threshold:g}s ({n} instances)
# regenerate:  cd benchmark && uv run python scripts/filter_sets.py
"""


def is_solved(rec: dict) -> bool:
    status = (rec.get("status") or "").lower()
    return bool(status) and "limit" not in status and "unsolved" not in status


def solve_time(rec: dict) -> float:
    """Mean runtime when repeated runs exist, else runtime_s."""
    t = rec.get("runtime_mean_s", rec.get("runtime_s"))
    return float(t) if t is not None else float("inf")


def load_records(version: str, solver: str,
                 results_root: Path,
                 machine: str | None) -> tuple[str, dict[str, dict], list[str]]:
    """Union of baseline records across all set dirs for this machine.

    Returns (machine, {instance: best record}, [set tags]). 'Best' = lowest
    measured solve time: classification asks what the baseline DEMONSTRATED
    on this machine, so any valid cached measurement under identical options
    counts.
    """
    base = results_root / solver / version
    if not base.is_dir():
        raise SystemExit(f"no results for {solver} {version}: {base}")
    machines = sorted(p.name for p in base.iterdir() if p.is_dir())
    if not machines:
        raise SystemExit(f"no machine dirs under {base}")
    if machine is None:
        if len(machines) > 1:
            raise SystemExit(
                f"multiple machines under {base}: {', '.join(machines)}\n"
                "pick one with --machine")
        machine = machines[0]
    elif machine not in machines:
        raise SystemExit(f"no results for machine {machine!r}; have: {', '.join(machines)}")

    best: dict[str, dict] = {}
    seen_sets: list[str] = []
    for set_dir in sorted((base / machine).iterdir()):
        if not set_dir.is_dir():
            continue
        seen_sets.append(set_dir.name)
        for f in sorted(set_dir.glob("*.json")):
            try:
                rec = json.loads(f.read_text())
            except (OSError, json.JSONDecodeError):
                continue
            inst = rec.get("instance") or f.stem
            prev = best.get(inst)
            if prev is None or _better(rec, prev):
                rec["_set"] = set_dir.name
                best[inst] = rec
    return machine, best, seen_sets


def _better(cand: dict, prev: dict) -> bool:
    """Prefer solved over unsolved; then lower measured time."""
    cs, ps = is_solved(cand), is_solved(prev)
    if cs != ps:
        return cs
    return solve_time(cand) < solve_time(prev)


def write_list(path: Path, name: str, instances: list[str], ctx: dict) -> None:
    lines = HEADER_TMPL.format(name=name, n=len(instances),
                               threshold=ctx["threshold"], **{k: v for k, v in ctx.items() if k != "threshold"})
    lines += "".join(f"{inst}\n" for inst in instances)
    path.write_text(lines)


def main() -> int:
    repo = Path(__file__).resolve().parents[2]
    default_subset_dir = repo / "benchmark" / "sets" / "subsets"
    ap = argparse.ArgumentParser(description="Generate super-fast/fast instance lists")
    ap.add_argument("--solver", default="highs")
    ap.add_argument("--version", default=DEFAULT_BASELINE,
                    help=f"baseline version to classify with (default {DEFAULT_BASELINE})")
    ap.add_argument("--set", default=DEFAULT_SET,
                    help=f"result-cache set tag to classify (default {DEFAULT_SET}); "
                         "classification uses only records for this set")
    ap.add_argument("--machine", default=None, help="machine dir (auto if unique)")
    ap.add_argument("--results-root", type=Path, default=None)
    ap.add_argument("--super-fast-below", type=float, default=DEFAULT_SUPER_FAST_BELOW)
    ap.add_argument("--fast-below", type=float, default=DEFAULT_FAST_BELOW)
    ap.add_argument("--out-super-fast", type=Path, default=None,
                    help="output for super-fast list (default sets/subsets/<set>-super-fast-instances.txt)")
    ap.add_argument("--out-fast", type=Path, default=None,
                    help="output for fast list (default sets/subsets/<set>-fast-instances.txt)")
    args = ap.parse_args()

    if args.super_fast_below >= args.fast_below:
        print("error: --super-fast-below must be < --fast-below")
        return 2
    root = args.results_root or results_dir()
    machine, records_by_inst, seen_sets = load_records(
        args.version, args.solver, root, args.machine)
    # Filter to requested set if it exists in cache (per-set classification)
    if args.set not in seen_sets:
        print(f"warning: set '{args.set}' not found among cached sets {seen_sets} — classifying over union")
    else:
        records_by_inst = {inst: rec for inst, rec in records_by_inst.items()
                           if rec.get("_set") == args.set}
        seen_sets = [args.set]
    records = list(records_by_inst.values())

    # Resolve default output paths based on set name
    if args.out_super_fast is None:
        args.out_super_fast = default_subset_dir / f"{args.set}-super-fast-instances.txt"
    if args.out_fast is None:
        args.out_fast = default_subset_dir / f"{args.set}-fast-instances.txt"

    limits = sorted({float(r.get("time_limit") or 0) for r in records})
    if len(limits) > 1:
        print(f"note: mixed time limits across source sets: {limits}")

    solved_times = {r["instance"]: solve_time(r)
                    for r in records if is_solved(r)}
    super_fast = sorted(i for i, t in solved_times.items()
                        if t < args.super_fast_below)
    fast = sorted(i for i, t in solved_times.items()
                  if t < args.fast_below)

    ctx = {
        "date": utcnow_iso(),
        "machine": machine,
        "solver": args.solver,
        "version": args.version,
        "src_sets": ", ".join(seen_sets),
        "n_total": len(records),
    }
    write_list(args.out_super_fast, "super-fast", super_fast,
               {**ctx, "threshold": args.super_fast_below})
    write_list(args.out_fast, "fast", fast,
               {**ctx, "threshold": args.fast_below})

    print(f"baseline: {args.solver} {args.version} @ {machine}")
    print(f"records: {len(records)}, solved: {len(solved_times)}")
    print(f"super-fast (<{args.super_fast_below:g}s): {len(super_fast)} -> {args.out_super_fast}")
    print(f"fast      (<{args.fast_below:g}s): {len(fast)} -> {args.out_fast}")
    print(f"full set  : all {len(records)} instances, 60s cap (implicit)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
